# 第 3 题  集合 set
#
# ① 在聊天里回答：集合和列表有什么区别？什么时候该用集合？

# ② 最小例子：判断 nums = [1, 2, 3, 2, 5] 里有没有重复元素，打印 True / False
#
# 你的代码：
nums=[1,2,3,4,5]
cur=set()
found=False
for x in nums:
    if x not in cur:
        cur.add(x)
    else:
        found=True
if found:
    print("True")
else:
    print("False")
