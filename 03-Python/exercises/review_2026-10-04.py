# 第 1 题  多组数据（必抽 —— 昨天中途空过一次）
#
# 输入格式（这是最常用的一种，和真题一模一样）：
#   第一行：T
#   接下来每组两行：
#     第一行：n
#     第二行：n 个用空格分开的整数
# 输出：每组输出一行的「这组整数的和」
#
# 自测输入：
# 3
# 5
# 1 2 3 4 5
# 1
# 10
# 2
# -3 3
#
# 期望输出：
# 15
# 10
# 0
#
# 你的代码：
T=int(input())
for _ in range(T):
    n=int(input())
    nums=list(map(int,input().split()))
    print(sum(nums))

