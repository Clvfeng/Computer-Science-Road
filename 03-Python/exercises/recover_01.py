# 第 4 题（循环 + 累加）
# 第一行读入整数 n，第二行读入 n 个整数（用空格隔开），输出它们的总和。
#
# 输入样例：
#   4
#   10 20 30 40
# 输出样例：
#   100
#
# 提示：一行里的多个数字可以用 map(int, input().split()) 一次读成整数列表。
# TODO:
n = int(input())
s = list(map(int,input().split()))
tolal = sum(s)
print(tolal)

