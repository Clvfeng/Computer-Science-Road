# 第 3 题（字符串切片）
# 读入一行文字，输出把它整个倒过来的样子。
#
# 输入样例：
#   hello
# 输出样例：
#   olleh
#
# 提示：字符串可以用"切片"取一部分，倒过来只要一个很短写法。
