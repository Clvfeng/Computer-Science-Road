# 第 2 题（送分题）
# 读入一个整数 n，在同一行输出 2n 和 n 的平方，两个数用空格隔开。
#
# 输入样例：
#   6
# 输出样例：
#   12 36
#
# 提示：print(值1, 值2) 会自动用空格隔开。
# TODO:
n = int(input())
print(2*n,n*n)



