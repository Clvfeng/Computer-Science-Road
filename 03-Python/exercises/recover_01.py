# 第 1 题（送分题）
# 读入两个整数 a 和 b（两个数在同一行，用空格隔开），输出它们的和。
#
# 输入样例：
#   3 5
# 输出样例：
#   8
#
# 提示：input() 读进来是"字符串"，不是数字。
