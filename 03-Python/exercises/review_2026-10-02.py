# 第 6 题  多组数据
# ① 题目第一行给一个 T，表示后面有 T 组数据，这种输入怎么读？
# ② 最小例子：第一行读 T，接下来读 T 个整数，每个乘以 2 并【分行】输出
#    自测输入用：3 / 10 / 20 / 30
#
# 你的代码：
T = int(input())          # T 单独占一行

for _ in range(T):
    n = int(input())      # ← 循环体里读，每次读一个
    print(n * 2)         # ← 每组输出一行，所以 print 在循环里面

