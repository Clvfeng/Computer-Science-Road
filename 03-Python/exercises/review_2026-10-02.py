# 第 5 题  预处理（用空间换时间）
# ① 什么情况下才值得"先建一张表"，而不是每次重新扫一遍？
#    触发条件是哪两条？（两条都必须说全）
#第一是数据规模大，第二是步骤相同要重复多次相同的步骤
# ② 最小例子：values = [5, 3, 5, 7, 3] ，
#    做出「每个数字第一次出现的下标」这张表
#
# 你的代码：
values=[5,3,5,7,3]
first={}
for i,v in enumerate(values):
    if v not in first:
        first[v]=i
print(first)
