# 第 2 题  二分找边界（10/5 到期）
# ① 找「第一个等于 k 的位置」时，命中之后为什么不能停？要继续做什么？
#因为可能不是下标最小的k，要继续往左继续找第一个位置
# ② 最小例子：a = [1, 2, 2, 2, 3, 5]，用二分找 2 的第一个位置（期望 1）
#
# 你的代码：
a=[1,2,2,2,3,5]
left=0
right=len(a)-1
k=int(input())
while left<=right :
    mid=(left+right)//2
    if a[mid]<k:
        left=mid+1
    elif a[mid]==k:
        temp=mid
        right=mid-1
    elif a[mid]>k:
        right=mid-1
print(temp)
