# 【题目描述】
# 某系统中有 n 个节点，每个节点有一个能量值。
# 现在需要从中选择一部分节点组成一个"稳定网络"，
# 要求网络中任意两个节点的能量值之差至少为 d。
# 请计算最多能选择多少个节点。
#
# 【输入格式】
# 第一行：两个整数 n 和 d（1 <= n <= 10^5，0 <= d <= 10^9），分别表示节点数量和最小能量差
# 第二行：n 个整数 A1..An（1 <= Ai <= 10^9），表示每个节点的能量值
#
# 【输出格式】
# 一行一个整数，表示最多能选择的节点数量
#
# 【样例】（原样例输出我这边读图没抓到，用下面这组）
# 输入：
#   11 2
#   3 1 4 1 5 9 2 6 5 3 5
# 输出：
#   ？  先自己手算出来填在这里：___4___
#       然后写代码跑一遍，看和手算一不一样
#
# 【提示】
# - "任意两个节点的能量值之差至少为 d" —— 在原数组顺序里看很麻烦
# - 但把数组先排好序之后，这个条件会变成什么？
#   想一下：排好序以后，如果每一对"相邻被选中的"都满足条件，
#   那么"任意两个"是不是自动就满足了？
# - 条件变简单之后，怎么选才能选得最多？（每次选尽可能小的，还是尽可能大的？）
# - n 到 10 万，你的做法能不能在 1 秒内跑完？
#
# TODO:

n, d = map(int, input().split())
nums = list(map(int, input().split()))
nums.sort()

picked = 1
last_picked = nums[0]
for i in range(1, n):
    if last_picked + d <= nums[i]:
        picked = picked + 1
        last_picked = nums[i]
print(picked)
