# 【题目描述】
# Maya 面前有 n 级台阶（1 < n < 1000），每次她可以向上跳 m 级台阶
# （不在中间的台阶上停留）。
# 台阶上有 k 个特殊的平台 p_i（k < 10），Maya 在该平台停留时会使得 m 增加 1。
# 请问 Maya 到达台阶顶部花费的时间。
#
# 【输入格式】
# 共 2 行。
#   第 1 行：3 个非负整数 n, m, k
#   第 2 行：k 个正整数，第 i 个表示 p_i，保证输入的 p_i 单调递增
#
# 【输出格式】
# 共 1 行，输出 1 个正整数，表示花费的时间。
#
# 【样例】
# 样例 1（k = 0 的时候第 2 行是空的；我读图只读到 "10 5" 两个数，
#        请你对照自己的截图确认这一行到底是不是 3 个数）
#   输入：
#     10 5 0
#   输出：
#     2
#
# 样例 2：
#   输入：
#     31 4 2
#     8 13
#   输出：
#     6
#
# 【先把"时间"的定义搞清楚】
# 跳一次 = 1 个单位时间。在平台上停一下**不额外花时间**，只是让 m 变大。
# 样例 2 我推了一遍，正好 6 跳，和输出对得上。
