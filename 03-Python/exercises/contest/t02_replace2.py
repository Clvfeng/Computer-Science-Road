# 天梯赛刷题 t02 —— 字符串替换
# 对应截图：微信图片_20260923104050_96_61.png + 微信图片_20260923104056_97_61.png
#
# 【题目背景】
# 众所周知：2 除 2 等于 1。
#
# 【题目描述】
# 给你一个数字，请你计算这个数字"除 2"的结果。
# 实际含义：把字符串里的每个 2 都变成 1，其他字符原样保留。
#
# 【输入格式】
# 一个数字 n（0 < n < 10^1000）
# 注意：因为有 1000 位，必须当成字符串读，不能用 int() 转整数。
#
# 【输出格式】
# 一个数字，表示 n 除 2 的结果
#
# 【样例 1】输入 23        → 输出 13
# 【样例 2】输入 2023      → 输出 1013
# 【样例 3】输入 20076584231272 → 输出 10076584131171
#   （样例 3 我读图时有点糊，位数请对照你自己的截图确认）
#
# 提示：字符串有一个现成的工具可以"整体替换"，见聊天里的工具箱。
#
# TODO:
num = input()
n_num = num.replace('2','1')
print(n_num)
