# t09 鸽子问题 —— 区间和是 m 的倍数（前缀和 + 鸽巢原理）
#
# ===== 题目 =====
# 一只鸽子住一个鸽巢，总共有 n 个鸽巢，每只鸽子都有自己的价值 a[i]。
# 养鸽人小云想拎出一个连续区间 l ~ r 的鸽子售卖，他希望卖出的价格是 m 的倍数
# （1 ≤ l ≤ r ≤ n）。小云只会养鸽子，不会数学，需要你告诉他这能不能做到。
#
# ===== 输入格式 =====
# 第一行一个正整数 T，表示共有 T 组测试数据（1 ≤ T ≤ 100）
# 每组测试数据：
#   第一行两个正整数 n, m（n ≤ 10^4，m ≤ 10^9）—— 鸽子数量、倍数要求
#   第二行 n 个整数，第 i 个表示第 i 只鸽子的价格（a[i] ≤ 10^7）
#
# ===== 输出格式 =====
# 每组输出一行：可以做到输出 Yes，否则输出 No
#
# ===== 样例（自造）=====
# 原截图里官方样例被截断了，下面是我造的等价样例：
#
# 输入：
# 3
# 5 3
# 1 2 3 4 5
# 3 100
# 1 2 4
# 2 1
# 7 8
#
# 输出：
# Yes
# No
# Yes
#
# ===== 目标 =====
# 目标 1（今天先做这个）：写出暴力版 —— 把所有 l ≤ r 都试一遍，求和判断。
#                        不许提前优化，先把正确性做出来，跑通上面三组数据。
# 目标 2（目标 1 过了再想）：让大数据（n = 10^4、T = 100）也不超时。
#
# ===== 提示 =====
# 提示 1：暴力就是两层循环，外层 l，内层 r，把 a[l] 到 a[r] 加起来。
# 提示 2：累加的时候想想 —— 内层循环能不能"边加边判断"，而不是每次都重新加。
#
# TODO: 目标 1 —— 暴力版




# TODO: 目标 2 —— 优化版
T=int(input())
for _ in range(T):
    n,m=map(int,input().split())
    values=list(map(int,input().split()))
    found=False
    pre=0
    s=set()
    s.add(0)
    for l in range(n):
        pre=pre+values[l]
        mod=pre%m
        if mod in s:
            found=True
            break
        else:
            s.add(mod)
    if found:
        print("Yes")
    else:
        print("No")
