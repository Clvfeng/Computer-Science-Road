#
# 【题目描述】
# 小佳的鸽子会说很多话，她的录音器记录下了鸽子一天说下的话，
# 是一个由大小写字母组成的字符串。小佳最喜欢她的鸽子咕咕咕，
# 但是她看不懂字符串，于是求助于你：
# 这个字符串里面有多少 gu（不论 gu 的大小写）？
#
# 【输入格式】
# 一个由大小写字母组成的字符串 s
#
# 【输出格式】
# 一个数字，表示字符串中 gu（gu、Gu、gU、GU 都算）的数量
#
# 【样例】
# 输入 GGGGugu  → 输出 2
#
# 【限制】
# 时间 1.0s，内存 256MB
#
# 提示：
# - "不论大小写"的常用做法是先把整串统一成小写，再统一去数
# - gu 是两个相邻字符凑成的，一个字符不能被用两次
#
# TODO:

s = input()
lower_s = s.lower()
print(lower_s.count("gu"))
