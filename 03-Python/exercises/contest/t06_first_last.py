# 【题目描述】
# 给定一个按照升序排列的长度为 n 的整数数组，以及 q 个查询。
# 对于每个查询，返回元素 k 在数组中的起始位置和终止位置（位置从 0 开始计数）。
# 如果数组中不存在该元素，则返回 -1 -1。
#
# 【输入格式】
# 第一行：整数 n 和 q，表示数组长度和询问个数
# 第二行：n 个整数（均在前 1..100000 范围内），表示完整数组
# 接下来 q 行：每行一个整数 k，表示一个询问元素
#
# 【输出格式】
# 共 q 行，每行两个整数，表示所求元素的起始位置和终止位置
# 不存在则输出 -1 -1
#
# 【数据范围】
# 1 <= n <= 100000
# 1 <= q <= 100000
# 1 <= k <= 100000
#
# 【样例】（题目原样例我这边读图没抓到，先用下面这组自测）
# 输入：
#   7 3
#   1 2 2 2 3 4 5
#   2
#   3
#   6
# 输出：
#   1 3
#   4 4
#   -1 -1
#
# 【提示】
# ★ 先看数据范围：n 和 q 都到 10 万。
#   如果你对每个查询都从头把整个数组扫一遍，最坏要扫 10万 x 10万 = 100 亿次，肯定超时。
#   想想能不能"提前把答案准备好"，让每次查询一步就能答出来。
#   你昨天学的字典，正好适合干这件事 —— 一个问题：
#   扫描数组的时候，每个数字需要记下哪两样信息，才能回答"起始位置和终止位置"？
#
# TODO:

n, q = map(int, input().split())
nums = list(map(int, input().split()))
queries = []
for _ in range(q):
    queries.append(int(input()))

first = {}
last = {}
for i in range(n):
    if nums[i] not in first:
        first[nums[i]] = i
    last[nums[i]] = i

for query in queries:
    if query in first:
        print(first[query], last[query])
    else:
        print(-1, -1)
