# ① 一句话：d[k] = d.get(k, 0) + 1 这行在干什么？
#    为什么不直接写 d[k] = d[k] + 1 ？
#累计计数，如果d[k]本来没有值就默认0再加1，有值直接加一
#安全取值，如果d[k]本来没有值直接写会出错
# ② 写代码：读入 n，然后 n 行每行一个单词；
#    输出每个单词出现的次数，按**第一次出现的顺序**，格式 `单词 次数`
#
# 你的代码：
n=int(input())
count={}
for _ in range(n):
    word=input()
    count[word]=count.get(word,0)+1
for k,v in count.items():
    print(k,v)
