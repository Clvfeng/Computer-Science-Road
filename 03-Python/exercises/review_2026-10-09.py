#往左边，因为第一个找到的k不一定是下标最小的
#
# ② 写代码：a = [1, 2, 2, 2, 3, 5]，找 k 的第一个位置。
#    要求：用二分，不许用 a.index / 不许遍历数组。
#    ⚠️ 找不到要输出 -1（昨天这里留了个坑）
#
# 你的代码：
a=[1,2,2,2,3,5]
k=int(input())
first=-1
left=0
right=len(a)-1
while left<=right:
    mid=(left+right)//2
    if a[mid]>k:
        right=mid-1
    elif a[mid]==k:
        right=mid-1
        first=mid
    elif a[mid]<k:
        left=mid+1
print(first)
