# 第 1 题  多组数据（昨天错了两个版本的题）
#
# 输入格式：
#   第一行：T（表示后面有 T 组数据）
#   接下来 T 行：每行若干个用空格分开的整数
# 输出：
#   每组输出一行的「这组整数的和」
#
# 自测输入：
# 3
# 1 2 3
# 10
# 5 5
#
# 期望输出：
# 6
# 10
# 10
#
# 你的代码：
T=int(input())
for _ in range(T):
    nums=list(map(int,input().split()))
    print(sum(nums))
