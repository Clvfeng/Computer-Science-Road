# 第 2 题  字典计数
#
# 输入：一行字符串（任意字符）
# 输出：每个字符各出现几次（把整个字典打印出来就行）
#
# 要求：不许事先把字符写死在代码里
#
# 自测输入 1：banana
# 自测输入 2：hello     ← 这组是重点，昨天第一版就是在这里崩的
#
# 你的代码：
word=input()
count={}
for w in word:
    count[w]=count.get(w,0)+1
print(count)

