# 第 3 题  enumerate
#
# 已知：values = [5, 3, 5, 7, 3]
# 输出：每个数字「第一次出现的下标」
# 期望输出：{5: 0, 3: 1, 7: 3}
#
# 要求：不许用手工计数器（count = count + 1）
#
# 你的代码：
values=[5,3,5,7,3]
first={}
for i,v in enumerate(values):
    if v not in first:
        first[v]=i
print(first)
