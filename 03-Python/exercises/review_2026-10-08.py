# 第 1 题  二分找边界（10/7 判生疏 → 今天必抽）
#
# 题目：一个升序数组 a，里面可能有重复值。
#       输入 n，然后一行 n 个整数，再输入一个 k。
#       输出 k 最后一次出现的下标；找不到输出 -1。
#
# ① 一句话：为什么"命中"之后不能直接停？指针该往哪边动？
# 第一个命中的不一定最大下标，往右移
#
# ② 写代码。要求：用二分，不许用 a.index / 不许遍历整个数组。
#    样例：n = 6, a = 1 2 2 2 3 5, k = 2  →  3
#
# 你的代码：
n=int(input())
a=list(map(int,input().split()))
k=int(input())
left=0
right=n-1
last=-1
while left<=right:
    mid=(left+right)//2
    if a[mid]>k:
        right=mid-1
    elif a[mid]==k:
        last=mid
        left=mid+1
    elif a[mid]<k:
        left=mid+1
print(last)
